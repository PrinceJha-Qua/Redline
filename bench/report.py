"""Write docs/BENCHMARK.md from the result files, so every number in it comes from a run.

    python bench/report.py
"""
import csv
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "bench" / "results"
OUT = ROOT / "docs" / "BENCHMARK.md"
TYPE_NAMES = {"non_existent_citation": "Non-existent citation", "case_name_mismatch": "Case name mismatch",
              "wrong_pincite": "Incorrect pin cite", "misquote": "Verbatim misquote",
              "content_misrepresentation": "Content misrepresentation"}
# Liu, Stammbach & Henderson (2026), Table 8 (recall, agentic) and Table 10 (false positives on 132 correct
# citations missing from CourtListener). Published numbers, not rerun here.
AGENTS = {"GPT-5 agent": {"non_existent_citation": 100.0, "case_name_mismatch": 100.0, "fp": 25.0},
          "Claude Code (Opus 4.8)": {"non_existent_citation": 93.5, "case_name_mismatch": 83.8, "fp": 10.9}}


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def pct(a, b):
    if not b:
        return "–"
    v = 100 * a / b
    return f"{v:.2f}%" if 0 < v < 1 else f"{v:.1f}%"


def _ho_first():
    """Redline errors on the fresh opinion sample's first run: the out-of-sample false-alarm rate."""
    run = load("false_alarms-holdout-firstrun")
    if not run:
        return "–"
    texterr = {e["citation"] for e in json.loads((ROOT / "bench" / "text_errors.json").read_text())["errors"]}
    r = sum(1 for f in run["flagged"] if f["citation"] not in texterr)
    return f"{100 * r / run['citations']:.3f}% of {run['citations']:,} real citations (unseen)"


def main():
    ev, ho, ho1 = load("phantom-eval"), load("phantom-aux_train"), load("phantom-aux_train-firstrun")
    fa, fa1, wild = load("false_alarms"), load("false_alarms-firstrun"), load("wild")
    src = json.loads((ROOT / "bench" / "source_errors.json").read_text())["errors"]
    txt = json.loads((ROOT / "bench" / "text_errors.json").read_text())["errors"]
    audit = ROOT / "bench" / "audit.csv"
    L = []
    w = L.append
    w("# Benchmarks\n")
    w(f"Generated by `make bench` on {date.today().isoformat()} from the files in `bench/results/`. "
      "Every number below comes from those files; rerun `make bench` to reproduce them.\n")
    w("Redline's promise is narrow: when it says **fabricated**, the citation cannot be right. So the first "
      "question is how often it calls a real citation fake, and only then how many fakes it catches.\n")

    w("## 1. Real citations: how often does Redline cry wolf?\n")
    w(f"A fixed random sample (seed {fa['seed']}) of {fa['opinions']} published opinions from the Caselaw Access "
      f"Project: {fa['sample']['f3d']} F.3d and {fa['sample']['us']} Supreme Court opinions. Every citation the "
      "judges wrote was checked. They are real citations, so every **fabricated** verdict is either a Redline "
      "error or an error in the digitized text.\n")
    w("| | Citations | Share |")
    w("|---|---:|---:|")
    w(f"| Checked | {fa['citations']:,} | |")
    for k in ("VERIFIED", "UNVERIFIABLE", "FABRICATED"):
        w(f"| {k.capitalize()} | {fa['verdicts'].get(k, 0):,} | {pct(fa['verdicts'].get(k, 0), fa['citations'])} |")
    w(f"| …of which errors in the opinion text (OCR or typo, each confirmed below) | {fa['text_errors']} | |")
    w(f"| **…of which Redline errors** | **{fa['redline_errors']}** | **{pct(fa['redline_errors'], fa['citations'])}** |")
    w("")
    texterr = {e["citation"] for e in json.loads((ROOT / "bench" / "text_errors.json").read_text())["errors"]}

    def split(run):
        t = sum(1 for f in run["flagged"] if f["citation"] in texterr)
        return t, len(run["flagged"]) - t

    rows = [("Tuning sample, first run", fa1), ("Tuning sample, now", fa),
            ("Fresh sample (never tuned on), first run", load("false_alarms-holdout-firstrun")),
            ("Fresh sample, now", load("false_alarms-holdout"))]
    w("Redline's rules were fixed while reading the tuning sample's flags, so a second, disjoint sample of "
      "opinions (another seed) was checked afterwards. Its **first run** is the out-of-sample number.\n")
    w("| Run | Opinions | Citations | Called fabricated | Text errors (confirmed) | **Redline errors** |")
    w("|---|---:|---:|---:|---:|---:|")
    for label, run in rows:
        if run:
            t, r = split(run)
            w(f"| {label} | {run['opinions']} | {run['citations']:,} | {len(run['flagged'])} | {t} | "
              f"**{r} ({100 * r / run['citations']:.3f}%)** |")
    w("")
    w("Every remaining flag points at text that really is wrong, for example `147 F.8d 1344`, where OCR read "
      "3 as 8. Pasted from a scanned PDF, those citations would mislead a reader too.\n")

    w("## 2. LePhantomCite: injected errors in real appellate briefs\n")
    w("[LePhantomCite](https://huggingface.co/datasets/ai-law-society-lab/Legal_Phantom_Citation) "
      "(Liu, Stammbach & Henderson 2026, CC BY 4.0) injects five kinds of citation error into excerpts of "
      "real federal appellate briefs. Scored per citation; a flag is a **fabricated** verdict. Typos the "
      "dataset marks `optional` are not scored. *Within reach* means the citation is to U.S. Reports or "
      "F.3d, or to a reporter series that was never published.\n")
    w("Redline's rules were tuned while reading the eval split's mistakes. The `aux_train` split was held "
      "out: its **first run** is the out-of-sample number.\n")
    w("| | Eval (tuned on) | Held out: first run | Held out: now |")
    w("|---|---:|---:|---:|")
    w(f"| Excerpts / citations checked | {ev['excerpts']} / {ev['citations_checked']:,} | {ho1['excerpts']} / {ho1['citations_checked']:,} | {ho['excerpts']} / {ho['citations_checked']:,} |")
    for r in (ev, ho1, ho):
        r["_flags"] = sum(v for k, v in r["flags"].items() if k != "optional")
    w(f"| Flags | {ev['_flags']} | {ho1['_flags']} | {ho['_flags']} |")
    w(f"| Injected errors among them | {ev['flags'].get('true_positive', 0)} | {ho1['flags'].get('true_positive', 0)} | {ho['flags'].get('true_positive', 0)} |")
    w(f"| Real typos in the original briefs, confirmed (listed below) | {ev['flags'].get('source_error', 0)} | {ho1['flags'].get('source_error', 0)} | {ho['flags'].get('source_error', 0)} |")
    w(f"| **Unexplained false alarms** | **{ev['flags'].get('false_positive', 0)}** | **{ho1['flags'].get('false_positive', 0)}** | **{ho['flags'].get('false_positive', 0)}** |")
    w(f"| Clean excerpts with any flag | {ev['clean_excerpts_with_a_flag']} of {ev['clean_excerpts']} | {ho1['clean_excerpts_with_a_flag']} of {ho1['clean_excerpts']} | {ho['clean_excerpts_with_a_flag']} of {ho['clean_excerpts']} |")
    w(f"| Time per excerpt | {ev['ms_per_excerpt']} ms | {ho1['ms_per_excerpt']} ms | {ho['ms_per_excerpt']} ms |")
    w("")
    w("Recall by error type (caught / within reach, and caught / all):\n")
    w("| Error type | Eval | Held out |")
    w("|---|---|---|")
    for t, name in TYPE_NAMES.items():
        a, b = ev["recall_by_type"][t], ho["recall_by_type"][t]
        w(f"| {name} | {a['caught_in_scope']}/{a['in_scope']} within reach · {a['caught']}/{a['total']} all | "
          f"{b['caught_in_scope']}/{b['in_scope']} within reach · {b['caught']}/{b['total']} all |")
    w("")
    w("Pin cites, misquotes and misrepresented holdings need the opinion's text, which Redline does not hold; "
      "it does not claim to catch them.\n")

    w("## 3. Next to AI agents\n")
    w("Published numbers from the same paper (Table 8: recall of agentic checkers; Table 10: share of 132 "
      "correct citations they wrongly flagged). They were not rerun here, and the test sets differ, so read "
      "this as a comparison of kind, not a leaderboard.\n")
    ne, cm = ev["recall_by_type"]["non_existent_citation"], ev["recall_by_type"]["case_name_mismatch"]
    w("| | Non-existent citation | Case name mismatch | Correct citations flagged | Cost per check |")
    w("|---|---:|---:|---:|---|")
    for name, a in AGENTS.items():
        w(f"| {name} | {a['non_existent_citation']}% | {a['case_name_mismatch']}% | {a['fp']}% | ~15 model steps |")
    w(f"| **Redline** (eval split) | {pct(ne['caught'], ne['total'])} | {pct(cm['caught'], cm['total'])} "
      f"({cm['caught_in_scope']}/{cm['in_scope']} within reach) | {_ho_first()} "
      f"| {ev['ms_per_excerpt']} ms, local, no model |")
    w("")
    w("Agents find more. Redline finds fewer, almost never flags a real citation, explains every flag with a "
      "page number, and costs nothing per check. The two are built to work together: Redline is an MCP tool an "
      "agent calls before it writes a citation.\n")

    if wild:
        w("## 4. Citations courts found fabricated\n")
        w(f"The [AI Hallucination Cases database](https://www.damiencharlotin.com/hallucinations/) (Damien Charlotin, "
          f"CC BY 4.0) lists {wild['us_cases']:,} US cases. For each *Fabricated: Case Law* item, Redline checked the "
          f"first citation the item quotes. {wild['fabricated_citations_in_scope']} fall within Redline's reach.\n")
        w("| Verdict | Citations |")
        w("|---|---:|")
        for k in ("FABRICATED", "UNVERIFIABLE", "VERIFIED"):
            w(f"| {k.capitalize()} | {wild['verdicts'].get(k, 0)} |")
        w("")
        w("The item text is the database's summary, not the brief: several items quote the real case the court "
          "found instead of the fake name, and some fakes were invented quotations from real cases. Those come "
          "back verified. Read the per-citation results in `bench/results/wild.json`.\n")

    audit_doc = json.loads((ROOT / "data" / "pagemap_audit.json").read_text())
    w("## 5. Auditing the data before trusting it\n")
    w(f"`bench/pagemap_audit.py` compares Redline's page maps with how courts actually cite each volume. Of "
      f"{audit_doc['cited_pages_checked']:,} pages that two or more courts cite as the start of a case, "
      f"{audit_doc['orphan_pages']:,} have no case starting there in the data, and {audit_doc['orphans_inside_another_case']:,} "
      "of those fall inside another case. Without this audit Redline would call every one of those real "
      "citations fake. Those pages are protected, and volumes with several of them are not used to prove "
      "fabrications (see `docs/DATA.md`).\n")

    w("## What the benchmarks changed\n")
    w("Each fix came from reading a false alarm:\n")
    for line in [
        "Pages that courts cite as a case's start are never called fabricated; volumes whose page maps disagree with courts are not used as proof.",
        "A page shared by two opinions (last page of one, first of the next) proves nothing.",
        "\"In re\" captions, relators and co-defendants: names are compared with the full caption, not just the short name.",
        "A short-form name proves a fake only when it matches a different case elsewhere in the same volume (\"Atkins, 536 U.S. 14\": Atkins v. Virginia is 536 U.S. 304).",
        "Spelling and OCR variants (Muñiz/Muniz, Cornejo/Camejo, Mann/Marin), abbreviations (Nat'l, Comm'r) and acronyms (NRDC, NAACP) match.",
        "Words common to many case names (Fire, Bank, Smith) need a second matching word.",
        "Reporter publication dates are trusted only for the reporters Redline holds; reporters-db dates are wrong for some series.",
        "Pages after the last opinion hold order lists (U.S.) or tables of unpublished decisions (F.3d), and so may a page with no case: all are unverifiable, not fabricated.",
        "A case name must lead straight into its citation (\"Name, 123 F.3d 456\"); words like \"If\" or \"and\" are not part of it; initials (\"J.J.\") and docket numbers (\"No. 93-1700\") are read correctly.",
        "A page number inside a parenthetical (\"109 S.Ct. 1865\") is not a year.",
    ]:
        w(f"- {line}")
    w("")

    w("## Adjudicated errors in the sources\n")
    w("A flag on one of these counts as correct only because the evidence shows the text really is wrong.\n")
    w("Typos in the original briefs (LePhantomCite does not label them):\n")
    w("| Citation in the brief | Evidence |")
    w("|---|---|")
    for e in src:
        w(f"| `{e['citation']}` | {e['evidence']} |")
    w("")
    w("Errors in the digitized opinion text:\n")
    w("| Citation in the text | Evidence |")
    w("|---|---|")
    for e in txt:
        w(f"| `{e['citation']}` | {e['evidence']} |")
    w("")

    w("## Not yet measured\n")
    judged = 0
    if audit.exists():
        judged = sum(1 for r in csv.DictReader(audit.open()) if (r.get("auditor_agrees") or "").strip())
    w(f"- **Hand audit.** `bench/audit.csv` holds a stratified sample of Redline verdicts on real opinions for a "
      f"person to judge; {judged} judged so far.")
    w("- **Agent experiment.** The same drafting task given to an agent with and without the Redline MCP tool. "
      "Needs an API key; not run yet.")
    w("- **Supreme Court after 2014.** Coverage ends with volume 572; later cases appear only as overruling records.")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
